export const propertyBySlug = (slug: string) => properties.find((p) => p.slug === slug);

export const forSale = properties.filter((p) => p.purpose === "sale");
export const forRent = properties.filter((p) => p.purpose === "rent");

export const featuredSales = forSale.filter((p) => p.featured);
export const featuredRentals = forRent.slice(0, 6);
export const exclusives = properties.filter((p) => p.exclusive);

export const byArea = (slug: string) => properties.filter((p) => p.areaSlug === slug);
export const byAgent = (slug: string) => properties.filter((p) => p.agentSlug === slug);

/** Similar listings: same area first, then same type, excluding the current listing. */
export function similarTo(current: string, limit = 3) {
  const p = propertyBySlug(current);
  if (!p) return [];
  const pool = properties.filter((x) => x.slug !== current && x.purpose === p.purpose);
  const sameArea = pool.filter((x) => x.areaSlug === p.areaSlug);
  const sameType = pool.filter((x) => x.areaSlug !== p.areaSlug && x.type === p.type);
  return [...sameArea, ...sameType, ...pool].slice(0, limit);
}

